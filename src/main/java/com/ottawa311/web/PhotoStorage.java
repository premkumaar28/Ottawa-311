package com.ottawa311.web;

import javax.servlet.ServletContext;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardOpenOption;
import java.util.UUID;

/** Stores photos outside the public web folder. */
final class PhotoStorage {
	
	private PhotoStorage() {
    }
	
	private static Path photoFolder(ServletContext context) throws IOException {
        String configuredFolder = System.getProperty("ottawa311.photo.dir");
        Path folder;

        if (configuredFolder == null || configuredFolder.trim().isEmpty()) {
            folder = Paths.get(System.getProperty("java.io.tmpdir"), "ottawa311-demo-photos");
        } else {
            folder = Paths.get(configuredFolder);
        }

        Files.createDirectories(folder);
        return folder;
    }
	
	/**
     * Save a photo with a random filename, unrelated to the report number.
     * Returns the actual filename to store in the report.
     */
    static String save(ServletContext context, String extension, byte[] photoBytes) throws IOException {
        if (!"jpg".equals(extension) && !"png".equals(extension)) {
            throw new IOException("Unsupported photo extension");
        }

        String filename = UUID.randomUUID().toString() + "." + extension;
        Path destination = photoFolder(context).resolve(filename);

        // CREATE_NEW will never overwrite an existing photo.
        Files.write(destination, photoBytes, StandardOpenOption.CREATE_NEW);
        return filename;
    }
    
    static byte[] load(ServletContext context, String filename) throws IOException {
        // Only accept the filenames generated by save(). No directory traversal.
        if (filename == null || !filename.matches(
                "[0-9a-fA-F-]{36}\\.(jpg|png)")) {
            throw new IOException("Invalid photo filename");
        }
        return Files.readAllBytes(photoFolder(context).resolve(filename));
    }
    
    /** Only call this for a filename created during the current request. */
    static void delete(ServletContext context, String filename) {
        try {
            if (filename != null && filename.matches("[0-9a-fA-F-]{36}\\.(jpg|png)")) {
                Files.deleteIfExists(photoFolder(context).resolve(filename));
            }
        } catch (IOException exception) {
            exception.printStackTrace();
        }
    }
	
}
